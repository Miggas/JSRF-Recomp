#!/usr/bin/env python3
"""Renderer backends plan, step 2: generate the backend dispatch from nv2a_rb.h.

  python3 gen_rb_dispatch.py <nv2a_rb.h> <out nv2a_rb_ops.h> <out nv2a_rb_names.h> <out nv2a_rb_dispatch.c> [<out nv2a_rb_queue.c>]

nv2a_rb_ops.h   RbOps: one pointer per rb_* call.
nv2a_rb_names.h for a backend file, included before nv2a_rb.h with
                RB_BACKEND_PREFIX(n) defined (e.g. rbgl_##n): renames its rb_*
                to its own names (calls inside the backend go straight to its
                own), and RB_OPS_TABLE(label) lists them in RbOps's order.
nv2a_rb_dispatch.c  the rb_* calls the renderer makes, through g_rb (the
                backend rb_select chose; OpenGL until then).
nv2a_rb_queue.c (vk13) a backend made of another: the calls in QUEUED below
                are written into a ring and made on a thread of their own
                (with copies of the data their pointers point at), every
                other call waits for that thread to catch up and runs on the
                caller's thread (nv2a_rb_queue_rt.h).
"""
import re, sys

src = open(sys.argv[1]).read()
t = re.sub(r'/\*.*?\*/', ' ', src, flags=re.S)
t = re.sub(r'//[^\n]*', ' ', t)
t = '\n'.join(l for l in t.split('\n') if not l.strip().startswith('#'))
t = re.sub(r'typedef\s+struct\s*\{[^{}]*\}\s*\w+\s*;', ' ', t, flags=re.S)
protos = []
for stmt in t.split(';'):
    st = ' '.join(stmt.split())
    m = re.match(r'^(.*?)\b(rb_[a-z0-9_]+)\s*\((.*)\)$', st)
    if not m:
        if 'rb_' in st:
            sys.exit('cannot read: ' + st)
        continue
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    if name in ('rb_select',):
        continue
    protos.append((ret, name, args))

def arg_names(args):
    if args in ('void', ''):
        return []
    out = []
    depth = 0; cur = ''
    for ch in args:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    out.append(cur)
    names = []
    for a in out:
        a = a.strip()
        m = re.search(r'\(\s*\*\s*(\w+)\s*\)', a)          # function pointer
        if m:
            names.append(m.group(1)); continue
        a = re.sub(r'\[[^\]]*\]$', '', a)                   # rgba[4]
        names.append(re.findall(r'\w+', a)[-1])
    return names

def ptr_member(ret, name, args):
    short = name[3:]
    return '%s (*%s)(%s);' % (ret, short, args) if not ret.endswith('*') else '%s(*%s)(%s);' % (ret, short, args)

H = []
w = H.append
w('/* Generated by jsrf_recomp/tools/gen_rb_dispatch.py from nv2a_rb.h -- do not edit. */')
w('#ifndef NV2A_RB_OPS_H')
w('#define NV2A_RB_OPS_H')
w('#include "nv2a_rb.h"')
w('')
w('/* one backend: every rb_* call */')
w('typedef struct RbOps {')
w('    const char *name;')
for ret, name, args in protos:
    w('    ' + ptr_member(ret, name, args))
w('} RbOps;')
w('')
w('/* the backend the rb_* calls go to from now on (before rb_init) */')
w('void rb_select(const RbOps *ops);')
w('extern const RbOps *g_rb;')
w('/* RECOMP_RB_PROFILE: every rb_* call counted and timed (nv2a_rb_dispatch.c) */')
w('void rb_prof_on(int on);')
w('int  rb_prof_enabled(void);')
w('int  rb_prof_report(char *buf, size_t n, uint64_t draws);')
w('#endif')
open(sys.argv[2], 'w').write('\n'.join(H) + '\n')

H = []
w = H.append
w('/* Generated by jsrf_recomp/tools/gen_rb_dispatch.py from nv2a_rb.h -- do not edit.')
w(' * For a backend file, before nv2a_rb.h: #define RB_BACKEND_PREFIX(n) rbgl_##n */')
w('#ifndef NV2A_RB_NAMES_H')
w('#define NV2A_RB_NAMES_H')
for ret, name, args in protos:
    w('#define %s RB_BACKEND_PREFIX(%s)' % (name, name[3:]))
w('#define RB_OPS_TABLE(label) { label, \\')
for i, (ret, name, args) in enumerate(protos):
    w('    %s%s' % (name, ', \\' if i < len(protos) - 1 else ' }'))
w('#endif')
open(sys.argv[3], 'w').write('\n'.join(H) + '\n')

C = []
w = C.append
w('/* Generated by jsrf_recomp/tools/gen_rb_dispatch.py from nv2a_rb.h -- do not edit.')
w(' * The renderer\'s rb_* calls, sent to the backend rb_select chose; with')
w(' * rb_prof_on (RECOMP_RB_PROFILE=1) each call is counted and timed. */')
w('#include "nv2a_rb_ops.h"')
w('#include "nv2a_tm.h"')
w('#include <stdio.h>')
w('#include <string.h>')
w('')
w('extern const RbOps rbgl_ops;            /* nv2a_rb_gl.c: the default */')
w('const RbOps *g_rb = &rbgl_ops;')
w('void rb_select(const RbOps *ops) { g_rb = ops; }')
w('')
w('#define RB_NCALLS %d' % len(protos))
w('static const char *const s_rb_names[RB_NCALLS] = {')
for i in range(0, len(protos), 6):
    w('    ' + ' '.join('"%s",' % n[3:] for _, n, _ in protos[i:i + 6]))
w('};')
w('static int s_prof;')
w('static uint64_t s_prof_n[RB_NCALLS], s_prof_t[RB_NCALLS];')
w('void rb_prof_on(int on) { s_prof = on; }')
w('int rb_prof_enabled(void) { return s_prof; }')
w('#define RB_P0 uint64_t t0_ = s_prof ? TM_NOW() : 0')
w('#define RB_P1(i) do { if (s_prof) { s_prof_n[i]++; s_prof_t[i] += TM_NOW() - t0_; } } while (0)')
w('')
w('/* the calls that took most time since the last report: one line */')
w('int rb_prof_report(char *buf, size_t n, uint64_t draws)')
w('{')
w('    int top[10], nt = 0, i, j;')
w('    uint64_t tot = 0;')
w('    double fq = 1000.0 / (double)SDL_GetPerformanceFrequency();')
w('    size_t k;')
w('    if (!s_prof || !buf || !n) return 0;')
w('    for (i = 0; i < RB_NCALLS; i++) {')
w('        tot += s_prof_t[i];')
w('        for (j = nt; j > 0 && s_prof_t[top[j - 1]] < s_prof_t[i]; j--)')
w('            if (j < 10) top[j] = top[j - 1];')
w('        if (j < 10) { top[j] = i; if (nt < 10) nt++; }')
w('    }')
w('    snprintf(buf, n, "%s backend %.0f ms, %.2f us a draw; most:", g_rb->name,')
w('             (double)tot * fq, draws ? (double)tot * fq * 1000.0 / (double)draws : 0.0);')
w('    for (i = 0; i < nt; i++) {')
w('        int c = top[i];')
w('        if (!s_prof_t[c]) break;')
w('        k = strlen(buf);')
w('        snprintf(buf + k, n - k, " %s %.0f ms (%.1f a draw, %.2f us each)", s_rb_names[c],')
w('                 (double)s_prof_t[c] * fq, draws ? (double)s_prof_n[c] / (double)draws : 0.0,')
w('                 s_prof_n[c] ? (double)s_prof_t[c] * fq * 1000.0 / (double)s_prof_n[c] : 0.0);')
w('    }')
w('    memset(s_prof_n, 0, sizeof s_prof_n);')
w('    memset(s_prof_t, 0, sizeof s_prof_t);')
w('    return 1;')
w('}')
w('')
for i, (ret, name, args) in enumerate(protos):
    names = arg_names(args)
    call = 'g_rb->%s(%s)' % (name[3:], ', '.join(names))
    sig = '%s%s%s(%s)' % (ret, '' if ret.endswith('*') else ' ', name, args)
    if ret == 'void':
        w('%s { RB_P0; %s; RB_P1(%d); }' % (sig, call, i))
    else:
        w('%s { RB_P0; %s r_ = %s; RB_P1(%d); return r_; }' % (sig, ret, call, i))
open(sys.argv[4], 'w').write('\n'.join(C) + '\n')
print('%d calls' % len(protos))


# ---------------------------------------------------------------- vk13 queue
if len(sys.argv) < 6:
    sys.exit(0)

VALUE = object()      # a pointer argument passed on as it is (a buffer offset)
# call -> {pointer argument: bytes to copy (C, may use the other arguments)}
QUEUED = {
    'fixed': {'f': 'sizeof(RbFixed)'}, 'fixed_lost': {}, 'use_program': {},
    'u1i': {}, 'u1ui': {}, 'u1f': {}, 'u2f': {}, 'u3f': {}, 'u4f': {},
    'u1iv': {'v': '(size_t)n * 4'}, 'u1uiv': {'v': '(size_t)n * 4'},
    'u1fv': {'v': '(size_t)n * 4'}, 'u2fv': {'v': '(size_t)n * 8'},
    'u3fv': {'v': '(size_t)n * 12'}, 'u4fv': {'v': '(size_t)n * 16'},
    'umat4': {'v': '(size_t)n * 64'},
    'bind_draw': {}, 'draw_bound_set': {}, 'viewport': {}, 'scissor': {},
    'scissor_once': {}, 'bindings_lost': {}, 'active_unit': {}, 'unit_bind': {},
    'bind_vbuf': {}, 'vbuf_lost': {}, 'vbuf_bound_set': {}, 'copy_target': {},
    'ms_upscale': {},
    'tex_image_dxt': {'data': '(size_t)size'},
    'tex_param': {}, 'tex_mipmaps': {}, 'tex_from_target': {}, 'errors_clear': {},
    'buf_bind': {}, 'buf_data': {'data': '(size_t)size'}, 'buf_sub': {'data': '(size_t)size'},
    'va_bind': {}, 'attr_on': {}, 'attr_off': {}, 'attr_pointer': {'ptr': VALUE},
    'attr_format': {}, 'attr_binding': {},
    'vbufs': {'bufs': '(size_t)n * sizeof(uint32_t)', 'offs': '(size_t)n * sizeof(intptr_t)',
              'strides': '(size_t)n * sizeof(int)'},
    'attr_const4fv': {'v': '16'}, 'attr_const4f': {},
    'draw_elements': {'off': VALUE}, 'draw_arrays': {},
    'clear': {'rgba': '16'},
    'query_begin': {}, 'query_end': {}, 'read_pixels_buf': {}, 'tex_bind_raw': {},
    'frame_end': {}, 'gpu_frame_mark': {},
}
# straight to the backend, from whatever thread, without waiting: constants
# and counters (some are asked for from the [PERF] thread, as before)
DIRECT = {'caps', 'shader_cache_on', 'shader_cache_path', 'max_aniso', 'window_stats',
          'gpu_frame_stats', 'program_stats', 'call_stats'}
OWN = {'threaded', 'thread_start', 'window_present'}      # written in nv2a_rb_queue_rt.h's terms below

def split_args(args):
    if args in ('void', ''):
        return []
    out = []; depth = 0; cur = ''
    for ch in args:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    out.append(cur.strip())
    return out

def arg_type(decl, name):
    if re.search(r'\[[^\]]*\]$', decl):                 # const float rgba[4]
        decl = re.sub(r'\[[^\]]*\]$', '', decl).strip()
        return decl[:decl.rfind(name)].strip() + ' *'
    return decl[:decl.rfind(name)].strip()

C = []
w = C.append
w('/* Generated by jsrf_recomp/tools/gen_rb_dispatch.py from nv2a_rb.h -- do not edit.')
w(' * vk13: rbq_ops, a backend made of another (rbq_wrap): the calls that return')
w(' * nothing are made on a thread of their own, in order; see nv2a_rb_queue_rt.h. */')
w('#include "nv2a_rb_ops.h"')
w('#define RB_NCALLS_Q %d' % len(protos))
w('#include "nv2a_rb_queue_rt.h"')
w('')
w('static const char *const q_names[RB_NCALLS_Q] = {')
for i in range(0, len(protos), 6):
    w('    ' + ' '.join('"%s",' % n[3:] for _, n, _ in protos[i:i + 6]))
w('};')
w('#define Q_AL(x) (((size_t)(x) + 15) & ~(size_t)15)')
w('')
execs = []
for i, (ret, name, args) in enumerate(protos):
    short = name[3:]
    names = arg_names(args)
    decls = split_args(args)
    sig = '%s%sq_%s(%s)' % (ret, '' if ret.endswith('*') else ' ', short, args)
    passthru = 'q_in->%s(%s)' % (short, ', '.join(names))
    if short in OWN:
        continue
    if short in DIRECT:
        w('static %s { %s%s; }' % (sig, '' if ret == 'void' else 'return ', passthru))
        continue
    if short not in QUEUED:
        w('static %s { if (q_on) q_drain(%d); %s%s; }' % (sig, i, '' if ret == 'void' else 'return ', passthru))
        continue
    if ret != 'void':
        sys.exit('queued call returns a value: ' + short)
    spec = QUEUED[short]
    fields = []; copies = []
    for d, n in zip(decls, names):
        t = arg_type(d, n)
        if '(' in d:
            sys.exit('queued call takes a function: ' + short)
        if '*' in t and n not in spec:
            sys.exit('queued call %s: pointer %s has no size' % (short, n))
        if n in spec and spec[n] is not VALUE:
            copies.append((n, t, spec[n]))
        else:
            fields.append((n, t))
    w('typedef struct {')
    for n, t in fields:
        w('    %s %s;' % (t, n))
    for n, t, sz in copies:
        w('    uint32_t z_%s;' % n)
    if not fields and not copies:
        w('    uint8_t unused_;')
    w('} QA_%s;' % short)
    w('static %s' % sig)
    w('{')
    w('    QA_%s *qa_;' % short)
    if copies:
        w('    uint8_t *qd_;')
        for n, t, sz in copies:
            w('    size_t z_%s = %s ? (size_t)(%s) : 0;' % (n, n, sz))
    w('    if (!q_on) { %s; return; }' % passthru)
    if copies:
        tot = ' + '.join('Q_AL(z_%s)' % n for n, _, _ in copies)
        w('    if (%s > RBQ_MAX_COPY) { q_drain(%d); %s; return; }' % (tot, i, passthru))
        w('    qa_ = (QA_%s *)q_begin(%d, Q_AL(sizeof *qa_) + %s);' % (short, i, tot))
    else:
        w('    qa_ = (QA_%s *)q_begin(%d, sizeof *qa_);' % (short, i))
    for n, t in fields:
        w('    qa_->%s = %s;' % (n, n))
    if copies:
        w('    qd_ = (uint8_t *)qa_ + Q_AL(sizeof *qa_);')
        for n, t, sz in copies:
            w('    qa_->z_%s = %s ? (uint32_t)z_%s : 0xFFFFFFFFu;' % (n, n, n))
            w('    if (%s) { memcpy(qd_, %s, z_%s); qd_ += Q_AL(z_%s); }' % (n, n, n, n))
    else:
        w('    (void)qa_;')
    w('    q_end();')
    w('}')
    # the reader's side
    E_ = []
    e = E_.append
    e('    case %d: {' % i)
    e('        const QA_%s *qa_ = (const QA_%s *)(h + 1);' % (short, short))
    if copies:
        e('        const uint8_t *qd_ = (const uint8_t *)qa_ + Q_AL(sizeof *qa_);')
        for n, t, sz in copies:
            e('        %s p_%s = NULL;' % (t, n))
            e('        if (qa_->z_%s != 0xFFFFFFFFu) { p_%s = (%s)qd_; qd_ += Q_AL(qa_->z_%s); }' % (n, n, t, n))
    callargs = []
    cp = {c[0] for c in copies}
    for n in names:
        callargs.append('p_' + n if n in cp else 'qa_->' + n)
    if not fields and not copies:
        e('        (void)qa_;')
    e('        q_in->%s(%s);' % (short, ', '.join(callargs)))
    if copies:
        e('        (void)qd_;')
    e('        break;')
    e('    }')
    execs += E_
w('')
w('static void q_exec(const RbqHdr *h)')
w('{')
w('    switch (h->op) {')
C += execs
w('    default: break;')
w('    }')
w('}')
w('')
w('/* the calls that are not simply passed on */')
w('static int q_threaded(void) { return q_on ? 1 : q_in->threaded(); }')
w('static void q_thread_start(void)')
w('{')
w('    q_in->thread_start();')
w('    if (!q_on && q_start())')
w('        fprintf(stderr, "[VK] draws recorded on a thread of their own (RECOMP_VK_RECORD_THREAD=0: on the renderer\'s)\\n");')
w('}')
w('/* every 600 frames, after the backend\'s own [VK] lines: the recording thread */')
w('static void q_report(void)')
w('{')
w('    static uint64_t l_busy;')
w('    double fq = 1000.0 / (double)SDL_GetPerformanceFrequency();')
w('    uint64_t busy = atomic_load(&q_busy_t);')
w('    int top[3] = { -1, -1, -1 }, i, j;')
w('    char tb[256] = "";')
w('    for (i = 0; i < RB_NCALLS_Q; i++) {')
w('        if (!q_drain_by[i]) continue;')
w('        for (j = 0; j < 3; j++)')
w('            if (top[j] < 0 || q_drain_t_by[i] > q_drain_t_by[top[j]]) {')
w('                memmove(top + j + 1, top + j, (size_t)(2 - j) * sizeof *top);')
w('                top[j] = i; break;')
w('            }')
w('    }')
w('    for (j = 0; j < 3 && top[j] >= 0; j++) {')
w('        size_t k = strlen(tb);')
w('        snprintf(tb + k, sizeof tb - k, "%s %s %llu (%.1f ms)", j ? "," : "; most:", q_names[top[j]],')
w('                 (unsigned long long)q_drain_by[top[j]], (double)q_drain_t_by[top[j]] * fq);')
w('    }')
w('    fprintf(stderr, "[VK]   recording thread: %.0f ms busy, %llu calls (%.1f MB); the renderer waited for it %llu times, %.1f ms in all%s%s\\n",')
w('            (double)(busy - l_busy) * fq, (unsigned long long)q_n_async, (double)q_bytes / 1048576.0,')
w('            (unsigned long long)q_n_drain, (double)q_drain_t * fq, tb,')
w('            q_n_space ? "; the queue was full" : "");')
w('    l_busy = busy;')
w('    q_n_async = q_bytes = q_n_drain = q_drain_t = q_n_space = 0;')
w('    memset(q_drain_by, 0, sizeof q_drain_by);')
w('    memset(q_drain_t_by, 0, sizeof q_drain_t_by);')
w('}')
w('static int q_window_present(const RbFrame *f)')
w('{')
w('    static uint64_t frames;')
w('    int r;')
w('    if (q_on) q_drain(%d);' % [n[3:] for _, n, _ in protos].index('window_present'))
w('    r = q_in->window_present(f);')
w('    if (q_on && ++frames % 600 == 0)')
w('        q_report();')
w('    return r;')
w('}')
w('')
w('static RbOps s_rbq_ops;')
w('/* `in` with its calls queued as above; its name stays */')
w('const RbOps *rbq_wrap(const RbOps *in)')
w('{')
w('    q_in = in;')
w('    s_rbq_ops.name = in->name;')
for ret, name, args in protos:
    w('    s_rbq_ops.%s = q_%s;' % (name[3:], name[3:]))
w('    return &s_rbq_ops;')
w('}')
open(sys.argv[5], 'w').write('\n'.join(C) + '\n')
print('queue: %d queued, %d direct' % (len(QUEUED), len(DIRECT)))
