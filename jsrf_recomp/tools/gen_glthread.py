#!/usr/bin/env python3
"""v172: generate nv2a_gl_thread.h -- every GL call nv2a_gl.c makes, recorded
into the GL thread's queue (nv2a_gl_thread_rt.h) or made directly.

  python3 gen_glthread.py <nv2a_gl.c> <glad gl.h> <out nv2a_gl_thread.h>

Each glX(...) in nv2a_gl.c becomes
  (s_glc[i]++, t_gt_mode == 1 ? gtr_glX(...) : glad_glX(...))
t_gt_mode is 1 only on the thread that records (the NV2A executor once the
GL thread runs); the GL thread itself and everything before it starts call
GL directly.

Kinds:
  async   no result, arguments by value; pointer arguments listed in PTRS are
          copied into the queue (their size given by an expression), others
          passed through as values (buffer offsets)
  sync    a result or memory written back: the call waits for the GL thread
          to reach it and make it (raw arguments, so pointers stay valid)
  special glFenceSync / glDeleteSync / glClientWaitSync (virtual fences) and
          the glGen* name pools, written by hand in nv2a_gl_thread_rt.h
"""
import re, sys

src = open(sys.argv[1]).read()
hdr = open(sys.argv[2]).read()
out = sys.argv[3]

s = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
s = re.sub(r'//[^\n]*', '', s)
s = re.sub(r'"(\\.|[^"\\])*"', '""', s)
names = sorted(set(re.findall(r'\b(gl[A-Z][A-Za-z0-9]*)\s*\(', s)))

# size expressions for copied pointer arguments, by argument index
PTRS = {
    'glBindVertexBuffers': {2: '(size_t)a1 * sizeof(GLuint)', 3: '(size_t)a1 * sizeof(GLintptr)',
                            4: '(size_t)a1 * sizeof(GLsizei)'},
    'glBufferData': {2: '(size_t)a1'},
    'glBufferSubData': {3: '(size_t)a2'},
    'glCompressedTexImage2D': {7: '(size_t)a6'},
    'glDeleteBuffers': {1: '(size_t)a0 * sizeof(GLuint)'},
    'glDeleteFramebuffers': {1: '(size_t)a0 * sizeof(GLuint)'},
    'glDeleteRenderbuffers': {1: '(size_t)a0 * sizeof(GLuint)'},
    'glDeleteTextures': {1: '(size_t)a0 * sizeof(GLuint)'},
    'glDeleteVertexArrays': {1: '(size_t)a0 * sizeof(GLuint)'},
    'glDeleteQueries': {1: '(size_t)a0 * sizeof(GLuint)'},
    'glTexImage2D': {8: 'gt_tex_bytes(a3, a4, a6, a7)'},
    'glTexSubImage2D': {8: 'gt_tex_bytes(a4, a5, a6, a7)'},
    'glUniform1fv': {2: '(size_t)a1 * 4'},
    'glUniform1iv': {2: '(size_t)a1 * 4'},
    'glUniform1uiv': {2: '(size_t)a1 * 4'},
    'glUniform2fv': {2: '(size_t)a1 * 8'},
    'glUniform3fv': {2: '(size_t)a1 * 12'},
    'glUniform4fv': {2: '(size_t)a1 * 16'},
    'glUniformMatrix4fv': {3: '(size_t)a1 * 64'},
    'glVertexAttrib4fv': {1: '16'},
}
# pointer arguments that are offsets into a bound buffer: passed as values
VALUE_PTRS = {'glDrawElementsBaseVertex': {3}, 'glVertexAttribPointer': {5}}
# no result and no pointers, but the caller relies on it having happened
FORCE_SYNC = {'glFinish', 'glFlush', 'glBufferStorage', 'glShaderSource', 'glProgramBinary'}
SPECIAL = {'glFenceSync': 'gtv_FenceSync', 'glDeleteSync': 'gtv_DeleteSync',
           'glClientWaitSync': 'gtv_ClientWaitSync',
           'glGenTextures': 'gtv_GenTextures', 'glGenFramebuffers': 'gtv_GenFramebuffers',
           'glGenRenderbuffers': 'gtv_GenRenderbuffers', 'glGenBuffers': 'gtv_GenBuffers',
           'glGenVertexArrays': 'gtv_GenVertexArrays', 'glGenQueries': 'gtv_GenQueries'}

funcs = []
for n in names:
    m = re.search(r'typedef (.*?) \(GLAD_API_PTR \*PFN%sPROC\)\((.*?)\);' % n.upper(), hdr)
    if not m:
        sys.exit('no prototype for ' + n)
    ret = m.group(1).strip()
    params = m.group(2).strip()
    types = []
    if params != 'void':
        for p in params.split(','):
            p = p.strip()
            mm = re.match(r'(.*?)(\w+)$', p)
            t = mm.group(1).strip()
            types.append(t)
    ptr_idx = [i for i, t in enumerate(types) if '*' in t]
    if n in SPECIAL:
        kind = 'special'
    elif ret != 'void' or n in FORCE_SYNC:
        kind = 'sync'
    else:
        copied = PTRS.get(n, {})
        vals = VALUE_PTRS.get(n, set())
        kind = 'async'
        for i in ptr_idx:
            if i not in copied and i not in vals:
                kind = 'sync'
    funcs.append((n, ret, types, kind))

L = []
w = L.append
w('/* Generated by jsrf_recomp/tools/gen_glthread.py from nv2a_gl.c -- do not edit.')
w(' * v172: the GL calls of nv2a_gl.c, made on the GL thread (see')
w(' * nv2a_gl_thread_rt.h). Counted for [PERF] GL calls as before. */')
w('#ifndef NV2A_GL_THREAD_H')
w('#define NV2A_GL_THREAD_H')
w('#define NV2A_GLC_N %d' % len(funcs))
w('static unsigned long long s_glc[NV2A_GLC_N];')
w('static const char *const s_glc_name[NV2A_GLC_N] = {')
for f in funcs:
    w('    "%s",' % f[0])
w('};')
w('enum {')
for i, f in enumerate(funcs):
    w('    GTF_%s = %d,' % (f[0], i + 16))
w('};')

def arglist(types):
    return ', '.join('%s a%d' % (t, i) for i, t in enumerate(types)) or 'void'

def callargs(types, fmt='a%d'):
    return ', '.join(fmt % i for i in range(len(types)))

# argument structs: raw (sync) for all, async with lengths for async ones
for n, ret, types, kind in funcs:
    if kind == 'special':
        continue
    w('typedef struct { %s } GTS_%s;' % (' '.join('%s a%d;' % (t, i) for i, t in enumerate(types)) or 'int unused;', n))

# record functions
for n, ret, types, kind in funcs:
    if kind == 'special':
        continue
    w('static %s gtr_%s(%s)' % (ret, n, arglist(types)))
    w('{')
    if kind == 'sync' or kind == 'async':
        pass
    if kind == 'async':
        copied = PTRS.get(n, {})
        if copied:
            # sizes; too big for the queue -> made synchronously
            for i in sorted(copied):
                w('    size_t l%d = a%d ? %s : 0;' % (i, i, copied[i]))
            tot = ' + '.join('GT_AL8(l%d)' % i for i in sorted(copied))
            cond = ' || '.join('l%d == (size_t)-1' % i for i in sorted(copied))
            w('    if (%s || %s > GT_INLINE_MAX) {' % (cond, tot))
            w('        GTS_%s s; %s' % (n, ' '.join('s.a%d = a%d;' % (i, i) for i in range(len(types)))))
            w('        gt_sync(GTF_%s, &s, NULL);' % n)
            w('        return;')
            w('    }')
            w('    {')
            w('        uint8_t *p = (uint8_t *)gt_begin(GTF_%s, GT_AL8(sizeof(GTS_%s)) + %s);' % (n, n, tot))
            w('        GTS_%s *s = (GTS_%s *)p;' % (n, n))
            w('        uint8_t *d = p + GT_AL8(sizeof(GTS_%s));' % n)
            for i, t in enumerate(types):
                if i in copied:
                    w('        if (a%d) { memcpy(d, a%d, l%d); s->a%d = (%s)(uintptr_t)1; d += GT_AL8(l%d); }'
                      ' else s->a%d = NULL;' % (i, i, i, i, t, i, i))
                else:
                    w('        s->a%d = a%d;' % (i, i))
            w('        gt_end();')
            w('    }')
        else:
            w('    GTS_%s *s = (GTS_%s *)gt_begin(GTF_%s, sizeof(GTS_%s));' % (n, n, n, n))
            for i in range(len(types)):
                w('    s->a%d = a%d;' % (i, i))
            w('    gt_end();')
    else:
        w('    GTS_%s s;' % n)
        for i in range(len(types)):
            w('    s.a%d = a%d;' % (i, i))
        if not types:
            w('    s.unused = 0;')
        if ret == 'void':
            w('    gt_sync(GTF_%s, &s, NULL);' % n)
        else:
            w('    %s r;' % ret)
            w('    gt_sync(GTF_%s, &s, &r);' % n)
            w('    return r;')
    w('}')

# replay of queued (async) commands
w('static void gt_replay(uint32_t id, uint8_t *p)')
w('{')
w('    switch (id) {')
for n, ret, types, kind in funcs:
    if kind != 'async':
        continue
    copied = PTRS.get(n, {})
    w('    case GTF_%s: {' % n)
    w('        GTS_%s *s = (GTS_%s *)p;' % (n, n))
    if copied:
        w('        uint8_t *d = p + GT_AL8(sizeof(GTS_%s));' % n)
        for i in sorted(copied):
            t = types[i]
            w('        %s c%d = NULL;' % (t, i))
            w('        if (s->a%d) { c%d = (%s)d; d += GT_AL8(%s); }' % (i, i, t,
              re.sub(r'\ba(\d+)', r's->a\1', copied[i])))
    args = []
    for i in range(len(types)):
        args.append('c%d' % i if i in copied else 's->a%d' % i)
    w('        glad_%s(%s);' % (n, ', '.join(args)))
    w('        break;')
    w('    }')
w('    default:')
w('        gt_replay_custom(id, p);')
w('    }')
w('}')

# synchronous calls (also the async ones made synchronously)
w('static void gt_replay_sync(uint32_t id, void *args, void *ret)')
w('{')
w('    switch (id) {')
for n, ret, types, kind in funcs:
    if kind == 'special':
        continue
    w('    case GTF_%s: {' % n)
    w('        GTS_%s *s = (GTS_%s *)args;' % (n, n))
    call = 'glad_%s(%s)' % (n, ', '.join('s->a%d' % i for i in range(len(types))))
    if ret == 'void':
        w('        %s;' % call)
    else:
        w('        *(%s *)ret = %s;' % (ret, call))
    w('        (void)s; (void)ret;')
    w('        break;')
    w('    }')
w('    default:')
w('        gt_replay_sync_custom(id, args, ret);')
w('    }')
w('}')

for i, (n, ret, types, kind) in enumerate(funcs):
    rec = SPECIAL.get(n, 'gtr_' + n)
    w('#undef %s' % n)
    w('#define %s(...) (s_glc[%d]++, t_gt_mode == 1 ? %s(__VA_ARGS__) : glad_%s(__VA_ARGS__))'
      % (n, i, rec, n))
w('#endif')
w('')
open(out, 'w').write('\n'.join(L))
print(len(funcs), 'functions:', sum(1 for f in funcs if f[3] == 'async'), 'queued,',
      sum(1 for f in funcs if f[3] == 'sync'), 'synchronous,',
      sum(1 for f in funcs if f[3] == 'special'), 'by hand')
for f in funcs:
    if f[3] == 'sync':
        print('  sync:', f[0])
