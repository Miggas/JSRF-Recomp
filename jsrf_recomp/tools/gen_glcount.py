import re, sys
src = open(sys.argv[1]).read()
# drop comments and strings so only real calls count
s = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
s = re.sub(r'//[^\n]*', '', s)
s = re.sub(r'"(\\.|[^"\\])*"', '""', s)
names = sorted(set(re.findall(r'\b(gl[A-Z][A-Za-z0-9]*)\s*\(', s)))
skip = {'glProgramBinary', 'glGetProgramBinary', 'glProgramParameteri', 'glQueryCounter'}
names = [n for n in names if n not in skip and not n.startswith('glad')]
out = ['/* v169: generated by gen_glcount.py -- counts the GL calls nv2a_gl.c makes',
       ' * (each one a crossing into the driver; under Proton a PE->unix call).',
       ' * Included after glad; -DNV2A_GL_NO_COUNT leaves the calls as they are. */',
       '#ifndef NV2A_GL_COUNT_H', '#define NV2A_GL_COUNT_H', '#ifndef NV2A_GL_NO_COUNT',
       '#define NV2A_GLC_N %d' % len(names),
       'static unsigned long long s_glc[NV2A_GLC_N];',
       'static const char *const s_glc_name[NV2A_GLC_N] = {']
out += ['    "%s",' % n for n in names]
out += ['};']
for i, n in enumerate(names):
    out += ['#undef %s' % n, '#define %s(...) (s_glc[%d]++, glad_%s(__VA_ARGS__))' % (n, i, n)]
out += ['#endif', '#endif', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print(len(names), 'functions')
