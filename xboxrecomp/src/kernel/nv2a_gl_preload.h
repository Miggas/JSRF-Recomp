/* Pending GL program objects for the lifetime of the renderer's single
 * context. The render thread owns this table. A first draw takes ownership
 * of its program so the usual variant eviction and deletion still apply. */
#ifndef NV2A_GL_PRELOAD_H
#define NV2A_GL_PRELOAD_H

#define PRELOAD_LIMIT 256
static struct {
    char path[64];                       /* generated by cache_path */
    GLuint id;
} s_preloaded[PRELOAD_LIMIT];
static unsigned s_preloaded_count;

static unsigned preloaded_find(const char *path)
{
    unsigned i;
    for (i = 0; i < s_preloaded_count; ++i)
        if (strcmp(path, s_preloaded[i].path) == 0)
            break;
    return i;
}

static GLuint preloaded_take(const char *path)
{
    unsigned i = preloaded_find(path);
    GLuint id;
    if (i == s_preloaded_count)
        return 0;
    id = s_preloaded[i].id;
    s_preloaded[i] = s_preloaded[--s_preloaded_count];
    return id;
}

static int preload_program(const char *path, const char *vsrc, const char *fsrc)
{
    GLuint id;
    if (preloaded_find(path) < s_preloaded_count)
        return 1;
    if (s_preloaded_count == PRELOAD_LIMIT || strlen(path) >= sizeof s_preloaded[0].path)
        return 0;
    /* Includes the ordinary recompile path for a stale or missing binary. */
    id = link_with2(vsrc, fsrc);
    if (!id)
        return 0;
    strcpy(s_preloaded[s_preloaded_count].path, path);
    s_preloaded[s_preloaded_count++].id = id;
    return 1;
}

#endif
